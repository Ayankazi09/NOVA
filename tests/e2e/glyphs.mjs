function rand(seed) {
  let s = seed
  return () => ((s = (s * 16807) % 2147483647) / 2147483647)
}

export async function drawText(page, text, x0, y0, size, seed, rise = 0) {
  const r = rand(seed)
  let x = x0
  let sup = false
  for (const ch of text) {
    if (ch === ' ') { x += size * 0.35; continue }
    if (ch === '^') { sup = true; continue }
    const glyph = G[ch]
    if (!glyph) throw new Error('no glyph ' + ch)
    const sz = sup ? size * 0.55 : size
    const gy = (sup ? y0 - size * 0.25 : y0 + (r() - 0.5) * 6) - rise * (x - x0)
    const slant = 0.12
    for (const stroke of glyph) {
      const pts = []
      for (let i = 0; i < stroke.length - 1; i++) {
        const [ax, ay] = stroke[i], [bx, by] = stroke[i + 1]
        for (let t = 0; t < 1; t += 0.2) pts.push([ax + (bx - ax) * t, ay + (by - ay) * t])
      }
      pts.push(stroke[stroke.length - 1])
      const P = pts.map(([px, py]) => [x + (px + (1 - py) * slant) * sz + (r() - 0.5) * 2, gy + py * sz + (r() - 0.5) * 2])
      await page.mouse.move(P[0][0], P[0][1])
      await page.mouse.down()
      for (const [px, py] of P.slice(1)) await page.mouse.move(px, py, { steps: 2 })
      await page.mouse.up()
      await page.waitForTimeout(40)
    }
    x += sz * 0.78
    sup = false
  }
  return x
}

