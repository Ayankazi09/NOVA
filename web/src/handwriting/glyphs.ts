// Built-in single-line handwriting glyphs. Unit box: y = 0 is the top of a digit, y = 1 the baseline,
// lowercase x-height starts at y ≈ 0.42, descenders reach y ≈ 1.32. Points are curve control points;
// the renderer passes a smooth Catmull-Rom spline through them, so few points give round strokes.

export type Pt = [number, number]
export interface Glyph {
  w: number // advance width (in heights)
  strokes: Pt[][]
}

const g = (w: number, ...strokes: Pt[][]): Glyph => ({ w, strokes })

// circle-ish loop helper: centre, radii, start angle (deg), sweep (deg), point count
function arc(cx: number, cy: number, rx: number, ry: number, from: number, sweep: number, n = 9): Pt[] {
  const out: Pt[] = []
  for (let i = 0; i < n; i++) {
    const a = ((from + (sweep * i) / (n - 1)) * Math.PI) / 180
    out.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)])
  }
  return out
}

